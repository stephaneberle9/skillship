import json
import zipfile

import pytest
from conftest import git, write_profile

from skillship import __version__
from skillship.cli import build_parser, main

PROFILE = (
    "recipient: ACME\ninclude: [billing:invoice-export]\ntargets:\n  - type: archive\n"
)


def run(source, *argv):
    return main(["-C", str(source), *argv])


def lock_text(source, name="acme"):
    return (source / "distros" / name / "distro.lock.yaml").read_text(encoding="utf-8")


def test_version_flag_prints_the_package_version(capsys):
    with pytest.raises(SystemExit) as exit_info:
        main(["--version"])
    assert exit_info.value.code == 0
    assert capsys.readouterr().out.strip() == f"skillship {__version__}"


def test_lock_needs_a_distro_name_or_all():
    with pytest.raises(SystemExit) as exit_info:
        build_parser().parse_args(["lock"])
    assert exit_info.value.code == 2


def test_lock_rejects_a_name_together_with_all():
    with pytest.raises(SystemExit):
        build_parser().parse_args(["lock", "acme", "--all"])


