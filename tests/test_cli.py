def test_lock_check_fails_on_a_renamed_file_and_shows_it(source, capsys):
    write_profile(source, "acme", PROFILE)
    run(source, "lock", "acme")
    git(source, "mv", "plugins/billing/skills/invoice-export/templates/export.md",
        "plugins/billing/skills/invoice-export/templates/out.md")  # fmt: skip
    before = lock_text(source)
    assert run(source, "lock", "acme", "--check") == 1
    out = capsys.readouterr().out
    assert "acme: lock is stale" in out
    assert "-  - templates/export.md\n+  - templates/out.md\n" in out
    assert lock_text(source) == before  # --check never writes


