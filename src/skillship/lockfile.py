"""The lock, `distros/<name>/distro.lock.yaml`: the resolved surface of a distro.

It lists skills, file paths and reasons, never content hashes, so editing the
text of a delivered file leaves it alone, while adding, removing or renaming a
file or skill, or changing a dependency, changes it. `build` reads the lock and
nothing else from the profile's resolution.
"""

from __future__ import annotations

import difflib
import hashlib
from pathlib import Path
from typing import Any

import yaml

from skillship.errors import SkillshipError
from skillship.profile import DISTROS_DIR, LOCK, Profile
from skillship.resolve import Resolution

HEADER = "# generated by skillship lock -- do not edit\n"
VERSION = 1


def lock_path(source_root: Path, name: str) -> Path:
    return source_root / DISTROS_DIR / name / LOCK


def render(profile: Profile, res: Resolution) -> str:
    layout: dict[str, Any] = {"shape": profile.shape, "root": profile.root}
    if profile.shape == "plugin":
        layout["name"] = profile.plugin_name
    if profile.shape in ("plugins", "plugin"):
        layout["marketplace"] = profile.marketplace or profile.name
    data: dict[str, Any] = {
        "lock-version": VERSION,
        "profile-digest": profile.digest,
        "layout": layout,
        "skills": [
            {"id": sid, "reason": res.skills[sid], "files": res.files[sid]}
            for sid in sorted(res.skills)
        ],
    }
    if res.extras:
        data["extras"] = sorted(res.extras)
    if res.plugins:
        plugins = []
        for p in res.plugins:
            entry: dict[str, Any] = {"name": p.name}
            if p.sources != [p.name]:
                entry["from"] = p.sources
            if p.description:
                entry["description"] = p.description
            entry["dependencies"] = p.dependencies
            plugins.append(entry)
        data["plugins"] = plugins
    if res.generated:
        data["generated"] = list(res.generated)
    if res.target_files:
        data["target-files"] = {
            tfs.name: _target_file_set(tfs) for tfs in res.target_files
        }
    if res.uploads:
        uploads: dict[str, Any] = {}
        if res.uploads.dropped:
            uploads["dropped-keys"] = {
                kind: dict(sorted(by_skill.items()))
                for kind, by_skill in res.uploads.dropped.items()
            }
        if res.uploads.inlined:
            uploads["inlined"] = sorted(res.uploads.inlined)
        if res.uploads.unresolved:
            uploads["unresolved"] = [
                {"target": u.target, "at": u.at, "path": u.path}
                for u in sorted(
                    res.uploads.unresolved, key=lambda u: (u.target, u.at, u.path)
                )
            ]
        data["uploads"] = uploads
    if res.rewritten:
        data["rewritten"] = dict(sorted(res.rewritten.items()))
    if res.unflattened:
        data["unflattened"] = [
            {"plugin": u.plugin, "at": u.at, "status": u.status}
            for u in sorted(res.unflattened, key=lambda u: (u.plugin, u.at))
        ]
    if res.suggested:
        data["suggested"] = [
            {"ref": ref, "by": sorted(by)} for ref, by in sorted(res.suggested.items())
        ]
    if res.dangling:
        data["dangling"] = [
            {"ref": d.ref, "at": d.at, "status": d.status}
            for d in sorted(res.dangling, key=lambda d: (d.ref, d.at))
        ]
    return HEADER + yaml.safe_dump(
        data, sort_keys=False, allow_unicode=True, width=1000
    )


def _target_file_set(tfs: Any) -> dict[str, Any]:
    out: dict[str, Any] = {}
    if tfs.gate:
        out["gate"] = tfs.gate
    files = []
    for f in tfs.files:
        entry = {"path": f.path, "from": f.source, "ownership": f.ownership}
        if f.forge:
            entry["forge"] = f.forge
        if f.mode:
            entry["mode"] = f.mode
        files.append(entry)
    out["files"] = files
    return out


def write(source_root: Path, profile: Profile, text: str) -> bool:
    """Write the lock; True when it changed."""
    path = lock_path(source_root, profile.name)
    old = (
        path.read_bytes().replace(b"\r\n", b"\n").decode("utf-8")
        if path.is_file()
        else None
    )
    if old == text:
        return False
    path.write_bytes(text.encode("utf-8"))
    return True


def stale_diff(source_root: Path, profile: Profile, text: str) -> str:
    """A unified diff from the committed lock to the current resolution; '' when current."""
    path = lock_path(source_root, profile.name)
    old = (
        path.read_bytes().replace(b"\r\n", b"\n").decode("utf-8")
        if path.is_file()
        else ""
    )
    if old == text:
        return ""
    rel = f"{DISTROS_DIR}/{profile.name}/{LOCK}"
    return "".join(
        difflib.unified_diff(
            old.splitlines(keepends=True),
            text.splitlines(keepends=True),
            fromfile=f"{rel} (committed)" if old else "/dev/null",
            tofile=f"{rel} (resolved)",
        )
    )


def load(source_root: Path, name: str) -> tuple[dict[str, Any], str]:
    """The lock's data and its digest."""
    path = lock_path(source_root, name)
    if not path.is_file():
        raise SkillshipError(
            f"no lock at {DISTROS_DIR}/{name}/{LOCK} -- run `skillship lock {name}`"
        )
    raw = path.read_bytes().replace(b"\r\n", b"\n")
    data = yaml.safe_load(raw)
    if not isinstance(data, dict) or data.get("lock-version") != VERSION:
        raise SkillshipError(
            f"{DISTROS_DIR}/{name}/{LOCK} is not a lock this version of skillship reads "
            f"(lock-version {VERSION}) -- run `skillship lock {name}`"
        )
    return data, "sha256:" + hashlib.sha256(raw).hexdigest()
